function record(
  id: string,
  name: string,
  context: string,
  status: string,
  owner: string,
  value: string,
  updated: string,
  description: string,
  facts: Record<string, string>,
  related: string[],
  source = "WasteHero",
  freshness = "Live",
  allowedTransitions?: string[],
  deepLink?: string,
): BusinessRecord {
  const fixtureScope = fixtureRecordScopeById[id]
  if (!fixtureScope) {
    throw new Error(`Missing explicit fixture scope for ${id}`)
  }
  const pointsToLegacyDemo =
    deepLink !== undefined &&
    ["/projects/", "/tasks", "/clients", "/inbox", "/performance", "/configure"].some(
      (legacyPath) => deepLink.startsWith(legacyPath),
    )

  return {
    id,
    name,
    context,
    status,
    owner,
    value,
    updated,
    description,
    facts,
    related,
    source,
    freshness,
    allowedTransitions,
    deepLink: pointsToLegacyDemo ? undefined : deepLink,
    companyId: fixtureScope.companyId,
    projectIds: [...fixtureScope.projectIds],
    serviceProviderId: fixtureScope.serviceProviderId,
  }
}

