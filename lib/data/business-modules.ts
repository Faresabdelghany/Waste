function requireWorkspaceModule(
  workspace: WorkspaceDefinition,
  moduleId: string,
): ModuleDefinition {
  const module = workspace.modules.find((candidate) => candidate.id === moduleId)
  if (!module) {
    throw new Error(`Missing ${moduleId} module in ${workspace.id}`)
  }
  return module
}

