function buildFixtureRecordScopeRegistry(): Readonly<
  Record<string, FixtureRecordScope>
> {
  const registry: Record<string, FixtureRecordScope> = {}
  const register = (
    recordIds: readonly string[],
    projectIds: readonly FixtureProjectId[],
  ) => {
    for (const recordId of recordIds) {
      if (registry[recordId]) {
        throw new Error(`Duplicate fixture scope for ${recordId}`)
      }

      registry[recordId] = {
        companyId: FIXTURE_COMPANY_ID,
        projectIds,
        serviceProviderId: fixtureServiceProviderIdByRecordId[recordId],
      }
    }
  }

  register(copenhagenFixtureRecordIds, [FIXTURE_PROJECT_IDS.copenhagen])
  register(harborFixtureRecordIds, [FIXTURE_PROJECT_IDS.harbor])
  register(seededCopenhagenContainerRecordIds, [FIXTURE_PROJECT_IDS.copenhagen])
  register(seededHarborContainerRecordIds, [FIXTURE_PROJECT_IDS.harbor])
  register(seededCopenhagenPropertyRecordIds, [FIXTURE_PROJECT_IDS.copenhagen])
  register(seededHarborPropertyRecordIds, [FIXTURE_PROJECT_IDS.harbor])
  register(companyWideFixtureRecordIds, [
    FIXTURE_PROJECT_IDS.copenhagen,
    FIXTURE_PROJECT_IDS.harbor,
  ])

  return Object.freeze(registry)
}

export const fixtureRecordScopeById = buildFixtureRecordScopeRegistry()

export type BusinessRecord = {
  id: string
  name: string
  context: string
  status: string
  owner: string
  value: string
  updated: string
  description: string
  facts: Record<string, string>
  related: string[]
  source: string
  freshness: string
  allowedTransitions?: string[]
  deepLink?: string
  /**
   * Fixture records always carry explicit scope. These remain optional so
   * temporary, client-created records can be introduced before persistence
   * assigns their canonical scope.
   */
  companyId?: string
  projectIds?: string[]
  serviceProviderId?: string
  /**
   * Client-created records retain their typed form payload and relation
   * references so later forms can use them as real upstream choices instead
   * of relying on flattened display text.
   */
  recordKind?: string
  submittedValues?: Record<string, string | boolean>
  relationRefs?: Array<{
    fieldId: string
    workspaceId: WorkspaceId
    moduleId: string
    recordId: string
    label: string
  }>
}

